-- Скрипт можно запускать повторно: он пересоздаёт таблицы с тестовыми данными.

IF DB_ID(N'Склад') IS NULL
    CREATE DATABASE Склад;
GO
USE Склад;
GO

IF OBJECT_ID(N'Загрузка_складов', N'V') IS NOT NULL DROP VIEW Загрузка_складов;
IF OBJECT_ID(N'Размещение', N'U') IS NOT NULL DROP TABLE Размещение;
IF OBJECT_ID(N'Накладные', N'U') IS NOT NULL DROP TABLE Накладные;
IF OBJECT_ID(N'Товары', N'U') IS NOT NULL DROP TABLE Товары;
IF OBJECT_ID(N'Склады', N'U') IS NOT NULL DROP TABLE Склады;
GO

-- Склады и их вместимость в упаковках
CREATE TABLE Склады (
    код_склада   int IDENTITY(1,1) PRIMARY KEY,
    название     nvarchar(100) NOT NULL UNIQUE,
    адрес        nvarchar(300) NULL,
    вместимость  int NOT NULL CHECK (вместимость > 0)
);

-- Справочник товаров
CREATE TABLE Товары (
    код_товара    int IDENTITY(1,1) PRIMARY KEY,
    наименование  nvarchar(200) NOT NULL UNIQUE
);

-- Принятые накладные (одну накладную нельзя принять дважды - первичный ключ)
CREATE TABLE Накладные (
    номер_накладной  nvarchar(30) PRIMARY KEY,
    дата             date NOT NULL,
    поставщик        nvarchar(200) NOT NULL,
    дата_приёма      datetime NOT NULL DEFAULT GETDATE()
);

-- Что, сколько и на каком складе лежит
CREATE TABLE Размещение (
    код_размещения   int IDENTITY(1,1) PRIMARY KEY,
    код_склада       int NOT NULL,
    код_товара       int NOT NULL,
    номер_накладной  nvarchar(30) NOT NULL,
    количество       int NOT NULL CHECK (количество > 0),
    FOREIGN KEY (код_склада)      REFERENCES Склады (код_склада),
    FOREIGN KEY (код_товара)      REFERENCES Товары (код_товара),
    FOREIGN KEY (номер_накладной) REFERENCES Накладные (номер_накладной)
);
GO

-- Загрузка складов: вместимость, занято, свободно (считает сервер, а не программа)
CREATE VIEW Загрузка_складов AS
SELECT с.код_склада,
       с.название,
       с.вместимость,
       ISNULL(SUM(р.количество), 0)                AS занято,
       с.вместимость - ISNULL(SUM(р.количество), 0) AS свободно
FROM Склады с
LEFT JOIN Размещение р ON р.код_склада = с.код_склада
GROUP BY с.код_склада, с.название, с.вместимость;
GO

-- Целостность: на склад нельзя положить больше, чем он вмещает
CREATE TRIGGER trg_Размещение_вместимость ON Размещение
AFTER INSERT, UPDATE
AS
BEGIN
    IF EXISTS (SELECT 1 FROM Загрузка_складов WHERE свободно < 0)
    BEGIN
        RAISERROR (N'Превышена вместимость склада', 16, 1);
        ROLLBACK TRANSACTION;
    END
END;
GO

